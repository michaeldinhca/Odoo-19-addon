from markupsafe import Markup

from odoo import _, api, fields, models
from odoo.exceptions import AccessError, UserError
from odoo.tools import format_amount


class RemittanceReconciliation(models.Model):
    """Ownership trail: one row per partial reconcile created by a payment registration.

    Recorded in the same transaction as the reconciliation, by comparing the partials that touch the
    payment and source lines before and after the native reconcile() call. That is what allows a
    bill/credit offset created by THIS registration to be told apart from any reconciliation that
    existed before it or was made after it.
    """
    _name = 'enterprise.remittance.reconciliation'
    _description = 'Remittance Reconciliation Ownership'
    _order = 'registration_id, id'

    registration_id = fields.Many2one(
        'enterprise.remittance.registration', required=True, readonly=True, index=True, ondelete='cascade')
    company_id = fields.Many2one(
        related='registration_id.company_id', store=True, index=True, readonly=True)
    company_currency_id = fields.Many2one(
        related='company_id.currency_id', string="Company Currency", readonly=True)

    kind = fields.Selection(
        [('payment', "Payment Application"),
         ('offset', "Bill/Credit Offset"),
         ('exchange', "Exchange Difference"),
         ('other', "Other")],
        required=True, readonly=True, index=True,
        help="Payment application: matches a document with the payment entry. Bill/credit offset: "
             "matches two documents selected together. Exchange difference: matches an exchange "
             "difference entry generated by the reconciliation.")
    partial_id = fields.Many2one(
        'account.partial.reconcile', string="Reconciliation", readonly=True, index=True, ondelete='set null',
        help="The partial reconciliation. Empty once it no longer exists.")
    partial_ref = fields.Integer(
        string="Reconciliation ID", readonly=True, index=True,
        help="Database id of the partial reconciliation at creation time, kept after it is removed.")
    debit_line_ref = fields.Integer(readonly=True, index=True)
    credit_line_ref = fields.Integer(readonly=True, index=True)
    debit_move_id = fields.Many2one('account.move', readonly=True, ondelete='set null')
    credit_move_id = fields.Many2one('account.move', readonly=True, ondelete='set null')
    debit_document = fields.Char(readonly=True)
    credit_document = fields.Char(readonly=True)
    amount = fields.Monetary(currency_field='company_currency_id', readonly=True)
    debit_currency_id = fields.Many2one('res.currency', readonly=True)
    credit_currency_id = fields.Many2one('res.currency', readonly=True)
    debit_amount_currency = fields.Monetary(currency_field='debit_currency_id', readonly=True)
    credit_amount_currency = fields.Monetary(currency_field='credit_currency_id', readonly=True)

    # Removal audit, stamped by account.partial.reconcile.unlink()
    removed_on = fields.Datetime(readonly=True)
    removed_by_id = fields.Many2one('res.users', readonly=True)
    removed_via = fields.Selection(
        [('reversed_by_user', "Reversed through the remittance wizard"),
         ('payment_cancel', "Payment cancelled"),
         ('payment_delete', "Payment deleted"),
         ('payment_draft', "Payment reset to draft"),
         ('external', "Removed by another action")],
        readonly=True)

    is_active = fields.Boolean(compute='_compute_is_active')
    reversal_status = fields.Selection(
        [('not_applicable', "Not applicable"), ('eligible', "Can be reversed"),
         ('blocked', "Cannot be reversed"), ('removed', "Already removed")],
        compute='_compute_reversal_status')
    reversal_blocker = fields.Char(compute='_compute_reversal_status')

    # ------------------------------------------------------------------
    # Compute
    # ------------------------------------------------------------------
    @api.depends('partial_id')
    def _compute_is_active(self):
        for row in self:
            row.is_active = bool(row.partial_id)

    @api.depends('partial_id', 'kind', 'registration_id.state')
    @api.depends_context('uid', 'allowed_company_ids', 'remittance_operation')
    def _compute_reversal_status(self):
        for row in self:
            if row.kind != 'offset':
                row.reversal_status, row.reversal_blocker = 'not_applicable', False
            elif not row.partial_id:
                row.reversal_status, row.reversal_blocker = 'removed', False
            else:
                eligible, message = row._reversal_check()
                row.reversal_status = 'eligible' if eligible else 'blocked'
                row.reversal_blocker = message or False

    # ------------------------------------------------------------------
    # Immutability
    # ------------------------------------------------------------------
    _MUTABLE_FIELDS = frozenset({'removed_on', 'removed_by_id', 'removed_via'})

    def write(self, vals):
        if set(vals) - self._MUTABLE_FIELDS:
            raise UserError(_("The reconciliation ownership trail is immutable."))
        return super().write(vals)

    @api.ondelete(at_uninstall=False)
    def _unlink_except_audit_history(self):
        raise UserError(_("The reconciliation ownership trail is audit history and cannot be deleted."))

    # ------------------------------------------------------------------
    # Reversal eligibility
    # ------------------------------------------------------------------
    def _reversal_check(self, operation=None):
        """Decide whether this offset may be reversed automatically.

        Reversal is refused (with a plain-language reason) unless every condition below holds. The
        rule of thumb: when ownership or safety cannot be proven, nothing is reversed.

        :return: (eligible, message)
        """
        self.ensure_one()
        operation = operation or self.env.context.get('remittance_operation') or 'offsets_only'
        if self.kind != 'offset':
            return False, _("Only a bill/credit offset can be reversed.")
        partial = self.partial_id
        if not partial:
            return False, _("This offset no longer exists.")
        # Ownership proof: the reconciliation is still exactly the one recorded at registration time.
        if partial.debit_move_id.id != self.debit_line_ref or partial.credit_move_id.id != self.credit_line_ref:
            return False, _("The reconciliation no longer matches the one recorded at registration.")
        if not partial.company_id.currency_id.is_zero(partial.amount - self.amount):
            return False, _("The reconciled amount changed since registration.")
        if operation == 'offsets_only' and self.registration_id.state == 'active':
            return False, _("The payment is still active. Cancel it first.")
        lines = partial.debit_move_id | partial.credit_move_id
        moves = lines.move_id
        if any(move.state != 'posted' for move in moves):
            return False, _("A document of this offset is no longer posted.")
        if not moves.company_id <= self.env.companies:
            return False, _("Enable %s in the company switcher to reverse it.", ", ".join(moves.company_id.mapped('name')))
        for move in moves:
            has_tax = bool(move.line_ids.tax_ids or move.line_ids.tax_line_id)
            if move.company_id._get_violated_lock_dates(move.date, has_tax, move.journal_id):
                return False, _("%s is in a locked accounting period.", move.display_name)
        # Later activity: another reconciliation touched one of the two lines after this offset.
        owned = set(self.registration_id.reconciliation_ids.mapped('partial_ref'))
        later = (lines.matched_debit_ids | lines.matched_credit_ids).filtered(
            lambda p: p.id > partial.id and p.id not in owned)
        if later:
            return False, _("The documents were reconciled again after this offset was created.")
        try:
            partial.check_access('unlink')
        except AccessError:
            return False, _("You do not have the access rights to unreconcile these entries.")
        return True, ''

    def _remittance_mark_removed(self, via):
        """Stamp who/when/how before the partial disappears (called from account.partial.reconcile.unlink)."""
        # sudo: the ownership trail is read-only for end users; this is a narrow audit stamp.
        self.sudo().write({
            'removed_on': fields.Datetime.now(),
            'removed_by_id': self.env.user.id,
            'removed_via': via,
        })

    def _remittance_describe(self):
        self.ensure_one()
        return Markup("%s / %s: %s") % (
            self.debit_document or '?', self.credit_document or '?',
            format_amount(self.env, self.amount, self.company_currency_id))

    def action_open_debit_document(self):
        self.ensure_one()
        return self.debit_move_id._get_records_action()

    def action_open_credit_document(self):
        self.ensure_one()
        return self.credit_move_id._get_records_action()
